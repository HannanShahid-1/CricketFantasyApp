// Generates src/generated/* from the web app, so the web stays the single source of truth:
//  - themes.ts: every theme's tokens, read from ../app/src/themes/*.css (+ order/default from themes.ts)
//  - photos.ts: player id -> bundled photo and list thumbnail, read from ../app/public/data/player-media.json
// Runs before `npm start`; run `npm run sync` after changing a web theme.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const web = join(root, '../app')
const out = join(root, 'src/generated')
const HEADER = '// Generated by scripts/sync-shared.mjs from the web app. Do not edit: run `npm run sync`.\n'

// ---------- themes ----------
const themesDir = join(web, 'src/themes')
const registry = readFileSync(join(themesDir, 'themes.ts'), 'utf8')
const order = [...registry.matchAll(/\{ id: '(\w+)', name: '([^']+)' \}/g)].map((m) => ({ id: m[1], name: m[2] }))
const defaultTheme = registry.match(/DEFAULT_THEME: ThemeId = '(\w+)'/)?.[1]

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const themes = {}
for (const f of readdirSync(themesDir).filter((f) => f.endsWith('.css'))) {
  const css = readFileSync(join(themesDir, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
  const block = css.match(/:root\[data-theme='(\w+)'\]\s*\{([^}]*)\}/)
  if (!block) continue
  const raw = { colorScheme: block[2].match(/color-scheme:\s*(\w+)/)?.[1] ?? 'dark' }
  for (const m of block[2].matchAll(/--([\w-]+):\s*([^;]+);/g)) raw[m[1]] = m[2].trim()
  const resolve = (v, depth = 0) =>
    depth > 5 ? v : v.replace(/var\(--([\w-]+)\)/g, (_, k) => resolve(raw[k] ?? '', depth + 1))
  const t = {}
  for (const [k, v] of Object.entries(raw)) t[camel(k)] = resolve(v)
  themes[block[1]] = t
}
const missing = order.filter((o) => !themes[o.id]).map((o) => o.id)
if (missing.length || !defaultTheme) throw new Error(`theme sync: missing ${missing.join(', ') || 'DEFAULT_THEME'}`)

writeFileSync(
  join(out, 'themes.ts'),
  `${HEADER}
export const THEME_ORDER = ${JSON.stringify(order, null, 2)} as const

export const DEFAULT_THEME = '${defaultTheme}'

export const THEME_TOKENS = ${JSON.stringify(themes, null, 2)} as const
`,
)

// ---------- player photos ----------
// Full photos for the player card; small thumbnails (generated with macOS `sips`) for list rows. A row shows a
// photo at 40pt at most, and decoding the 384px originals there costs ~0.6 MB of memory per player scrolled past.
const THUMB_PX = 144 // 48pt at 3x
const media = JSON.parse(readFileSync(join(web, 'public/data/player-media.json'), 'utf8'))
const photos = Object.entries(media.players).filter(([, p]) => p.photo).map(([id, p]) => [id, join(web, 'public', p.photo)])
const thumbsDir = join(out, 'thumbs')
const thumbOf = (src) => join(thumbsDir, basename(src).replace(/\.\w+$/, '.heic'))
mkdirSync(thumbsDir, { recursive: true })
const stale = photos.map(([, src]) => src).filter((src) => !existsSync(thumbOf(src)) || statSync(thumbOf(src)).mtimeMs < statSync(src).mtimeMs)
let thumbs = true
if (stale.length) {
  try {
    execFileSync('sips', ['-s', 'format', 'heic', '-Z', String(THUMB_PX), ...stale, '--out', thumbsDir], { stdio: 'ignore' })
  } catch {
    thumbs = false // no sips (not macOS): rows fall back to the full photos
  }
}
const entry = (id, file) => {
  const rel = relative(out, file)
  return `  '${id}': require('${rel.startsWith('.') ? rel : `./${rel}`}'),`
}
writeFileSync(
  join(out, 'photos.ts'),
  `${HEADER}/* eslint-disable */
/** player id -> full photo (player card) */
export const PHOTOS: Record<string, number> = {
${photos.map(([id, src]) => entry(id, src)).join('\n')}
}

/** player id -> ${THUMB_PX}px thumbnail (list rows and avatars) */
export const THUMBS: Record<string, number> = ${thumbs ? `{
${photos.map(([id, src]) => entry(id, thumbOf(src))).join('\n')}
}` : 'PHOTOS'}
`,
)

console.log(`sync: ${order.length} themes (default ${defaultTheme}), ${photos.length} photos, ${stale.length} new thumbnails`)
